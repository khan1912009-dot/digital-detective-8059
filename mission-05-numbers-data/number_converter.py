# Decimal to Binary
print("13 in binary:", bin(13))
print("25 in binary:", bin(25))

# Binary to Decimal
print("1010 in decimal:", int("1010", 2))
print("1101 in decimal:", int("1101", 2))

# Hexadecimal to Decimal
print("A in decimal:", int("A", 16))
print("1F in decimal:", int("1F", 16))

# Binary to Hexadecimal
print("1111 in hexadecimal:", hex(int("1111", 2)))